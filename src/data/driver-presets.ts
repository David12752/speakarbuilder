/**
 * Get presets filtered by driver type.
 */
export function getPresetsByType(type: DriverParams['type']): DriverPreset[] {
    return DRIVER_PRESETS.filter(p => p.type === type)
}

/**
 * Search presets by name or manufacturer.
 */
export function searchPresets(query: string): DriverPreset[] {
    const q = query.toLowerCase()
    return DRIVER_PRESETS.filter(p =>
        p.name.toLowerCase().includes(q) ||
        p.manufacturer.toLowerCase().includes(q) ||
        p.model.toLowerCase().includes(q) ||
        p.category.toLowerCase().includes(q)
    )
}
